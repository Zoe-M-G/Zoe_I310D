def calculate_volume_of_sphere(radius):
  pi = 3.14
  volume = radius**3 * pi * 4/3
  return volume

radius1 = 30
print(f"The volume of a sphere with radius {radius1} is: {calculate_volume_of_sphere(radius1)}")

radius2 = 40
print(f"The volume of a sphere with radius {radius2} is: {calculate_volume_of_sphere(radius2)}")
	